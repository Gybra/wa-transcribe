#!/usr/bin/env bash
#
# Registers the wa-transcribe native messaging host for Chrome and Brave.
# Requires macOS on Apple Silicon (MLX) and ffmpeg (brew install ffmpeg).
#
# Optional env:
#   WA_TRANSCRIBE_VENV  venv with mlx-audio (default ~/.venvs/wa-transcribe, created if missing)

set -euo pipefail

ROOT="$(cd "$(dirname "$0")" && pwd)"
VENV="${WA_TRANSCRIBE_VENV:-$HOME/.venvs/wa-transcribe}"
# Derived from the "key" in extension/manifest.json: fixed wherever the folder lives.
EXTENSION_ID="mnebcjapfkcbmhgnhoehoalfboicdihh"
# Hosts inherit the browser's privacy permissions, which usually exclude
# Documents, Desktop and Downloads: install outside of the repository.
HOST_DIR="$HOME/Library/Application Support/wa-transcribe"
LAUNCHER="$HOST_DIR/wa-transcribe-host"

die() { echo "❌ $*" >&2; exit 1; }

[[ "$(uname -sm)" == "Darwin arm64" ]] || die "MLX needs macOS on Apple Silicon"
FFMPEG="$(command -v ffmpeg)" || die "ffmpeg not installed (brew install ffmpeg)"

if [[ ! -x "$VENV/bin/python" ]]; then
    # mlx-audio needs Python 3.10+, while macOS's own python3 is 3.9.
    PYTHON=""
    for CANDIDATE in python3 python3.14 python3.13 python3.12 python3.11 python3.10; do
        if "$CANDIDATE" -c "import sys; sys.exit(sys.version_info < (3, 10))" 2>/dev/null; then
            PYTHON="$CANDIDATE"
            break
        fi
    done
    [[ -n "$PYTHON" ]] || die "Python 3.10+ not installed (brew install python)"
    "$PYTHON" -m venv "$VENV"
    "$VENV/bin/pip" install -q --upgrade pip
fi

# mlx-audio changes its API often: enforce the version this host was tested
# with on every run, also in an existing venv.
echo "⚙️  Installing mlx-audio 0.6.4 in $VENV ..."
"$VENV/bin/pip" install -q mlx-audio==0.6.4

# The host runs offline, so the model must already be in the Hugging Face cache.
echo "⬇️  Checking the Qwen3-ASR model (first run downloads ~2.5 GB) ..."
"$VENV/bin/python" -c "
import sys; sys.path.insert(0, '$ROOT/host')
import huggingface_hub, wa_transcribe
huggingface_hub.snapshot_download(wa_transcribe.MODEL)"

mkdir -p "$HOST_DIR"
cp "$ROOT/host/wa_transcribe.py" "$HOST_DIR/"
# Browsers start native hosts with a minimal PATH: pin ffmpeg's directory.
cat > "$LAUNCHER" <<EOF
#!/bin/sh
# Generated by install.sh.
export PATH="$(dirname "$FFMPEG"):/usr/bin:/bin"
exec "$VENV/bin/python" "$HOST_DIR/wa_transcribe.py"
EOF
chmod +x "$LAUNCHER"

INSTALLED=0
for BROWSER in "Google/Chrome" "BraveSoftware/Brave-Browser"; do
    DIR="$HOME/Library/Application Support/$BROWSER"
    [[ -d "$DIR" ]] || continue
    mkdir -p "$DIR/NativeMessagingHosts"
    cat > "$DIR/NativeMessagingHosts/wa_transcribe.json" <<EOF
{
  "name": "wa_transcribe",
  "description": "wa-transcribe: local Qwen3-ASR transcription of WhatsApp Web voice messages",
  "path": "$LAUNCHER",
  "type": "stdio",
  "allowed_origins": ["chrome-extension://$EXTENSION_ID/"]
}
EOF
    echo "✅ Registered for $BROWSER"
    INSTALLED=1
done
[[ "$INSTALLED" == 1 ]] || die "neither Chrome nor Brave found"

echo "Now load $ROOT/extension as an unpacked extension and reload WhatsApp Web."
